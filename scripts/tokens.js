// Write src/renderer/tokens.css from design/tokens.json, and check the colour pairs against WCAG AA.
//
//   npm run tokens      after editing design/tokens.json
//
// test/design.test.js runs the same functions: it fails when tokens.css is out of date, when a pair misses AA,
// or when the stylesheet uses a variable the tokens do not define.

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const SOURCE = path.join(root, 'design', 'tokens.json');
const OUT = path.join(root, 'src', 'renderer', 'tokens.css');

// ---- colour arithmetic (WCAG 2)

function rgba(hex) {
  const h = hex.replace('#', '');
  const n = h.length === 3 ? h.split('').map(c => c + c).join('') : h;
  if (!/^[0-9a-f]{6}([0-9a-f]{2})?$/i.test(n)) throw new Error(`not a colour: ${hex}`);
  const v = [0, 2, 4, 6].map(i => parseInt(n.slice(i, i + 2) || 'ff', 16));
  return {r: v[0], g: v[1], b: v[2], a: v[3] / 255};
}

// A tint laid over an opaque colour.
function over(top, base) {
  const t = rgba(top), b = rgba(base);
  const mix = k => Math.round(t[k] * t.a + b[k] * (1 - t.a));
  return '#' + ['r', 'g', 'b'].map(k => mix(k).toString(16).padStart(2, '0')).join('').toUpperCase();
}

function luminance(hex) {
  const c = rgba(hex);
  const lin = v => { v /= 255; return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; };
  return 0.2126 * lin(c.r) + 0.7152 * lin(c.g) + 0.0722 * lin(c.b);
}

function ratio(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

const NEEDS = {normal: 4.5, large: 3, ui: 3};

// Every pair in one theme: [{fg, bg, kind, ratio, needs, ok}].
function checkPairs(colors, pairs) {
  return pairs.map(([fg, bg, kind = 'normal', base]) => {
    for (const k of [fg, bg, base].filter(Boolean)) if (!colors[k]) throw new Error(`pair names an unknown colour: ${k}`);
    const opaque = name => (rgba(colors[name]).a < 1 ? over(colors[name], colors[base || 'surface']) : colors[name]);
    const back = opaque(bg);
    const front = rgba(colors[fg]).a < 1 ? over(colors[fg], back) : colors[fg];
    const r = ratio(front, back);
    return {fg, bg: base ? `${bg} over ${base}` : bg, kind, ratio: r, needs: NEEDS[kind], ok: r >= NEEDS[kind]};
  });
}

// ---- the stylesheet

function css(tokens) {
  const block = (vars, indent) => Object.entries(vars).map(([k, v]) => `${indent}--${k}: ${v};`).join('\n');
  const px = (obj, prefix) => Object.fromEntries(Object.entries(obj).map(([k, v]) => [`${prefix}${k}`, `${v}px`]));
  const type = Object.fromEntries(Object.entries(tokens.type).map(([k, v]) => [`fs-${k}`, `${v.size}px`]));
  const light = {
    ...tokens.color,
    ...Object.fromEntries(Object.entries(tokens.font).map(([k, v]) => [k, v])),
    ...type,
    'tracking-label': tokens.type.label.tracking,
    'lh-read': String(tokens.type.read.line),
    ...px(tokens.space, 'sp-'),
    ...px(tokens.radius, 'r-'),
    ...tokens.shadow,
    ...tokens.motion,
    ...tokens.layout,
  };
  const dark = {...tokens['color-dark'], ...tokens['shadow-dark']};
  return [
    '/* Generated by scripts/tokens.js from design/tokens.json. Edit the JSON, then run npm run tokens. */',
    '',
    ':root {',
    block(light, '  '),
    '',
    '  color-scheme: light dark;',
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    '  :root {',
    block(dark, '    '),
    '  }',
    '}',
    '',
  ].join('\n');
}

const load = () => JSON.parse(fs.readFileSync(SOURCE, 'utf8'));

function report(tokens) {
  let failed = 0;
  for (const theme of ['color', 'color-dark']) {
    for (const p of checkPairs(tokens[theme], tokens.pairs)) {
      if (!p.ok) failed++;
      if (!p.ok || process.argv.includes('--all')) {
        console.log(`${p.ok ? 'ok  ' : 'FAIL'} ${theme === 'color' ? 'light' : 'dark '} ${p.fg} on ${p.bg}: ${p.ratio.toFixed(2)} (needs ${p.needs})`);
      }
    }
  }
  return failed;
}

if (require.main === module) {
  const tokens = load();
  fs.writeFileSync(OUT, css(tokens));
  const failed = report(tokens);
  console.log(`Wrote ${path.relative(root, OUT)}; ${tokens.pairs.length * 2} pairs checked, ${failed} below AA.`);
  if (failed) process.exit(1);
}

module.exports = {load, css, checkPairs, ratio, over, OUT};
